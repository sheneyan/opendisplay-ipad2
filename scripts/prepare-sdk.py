#!/usr/bin/env python3
"""Prepare the pinned legacy SDK's link stubs for modern ld-classic.

Requires PyYAML. Does not add runtime symbols or replace system libraries.
The original mixed device/simulator v1 stubs confuse modern TAPI. Select
only their existing armv7 exports. The SDK's dangling liblaunch re-export
is removed; this app does not import launch_* symbols. Restore missing
declarations for memcpy/memchr from the standard C libSystem ABI.
"""
from pathlib import Path
import re
import shutil
import yaml

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / '.toolchain/sdks/iPhoneOS9.3.sdk'
output = ROOT / '.toolchain/prepared/iPhoneOS9.3.sdk'
if not source.is_dir():
    raise SystemExit('Fetch the legacy SDK as described in README.md first.')
if output.is_dir():
    # This exact directory is generated by this script, never the source SDK.
    shutil.rmtree(output)
shutil.copytree(source, output, symlinks=True, dirs_exist_ok=True)
count = 0
for path in output.rglob('*.tbd'):
    if path.is_symlink():
        continue
    text = re.sub(r'^---[^\n]*', '---', path.read_text(), count=1)
    documents = []
    for document in yaml.safe_load_all(text):
        if not document or 'armv7' not in document.get('archs', []):
            continue
        document['archs'] = ['armv7']
        for section in ('exports', 'reexports', 'undefineds'):
            if section in document:
                document[section] = [
                    {**entry, 'archs': ['armv7']}
                    for entry in document[section]
                    if 'armv7' in entry.get('archs', [])
                ]
        for entry in document.get('exports', []):
            if 're-exports' in entry:
                entry['re-exports'] = [
                    name for name in entry['re-exports']
                    if name != '/usr/lib/system/liblaunch.dylib'
                ]
        if path.name == 'libSystem.tbd':
            document.setdefault('exports', []).append({
                'archs': ['armv7'], 'symbols': ['_memcpy', '_memchr'],
            })
        documents.append(document)
    if documents:
        path.write_text(yaml.safe_dump_all(documents, explicit_start=True,
                                          explicit_end=True, sort_keys=False, width=110))
        count += 1
print(f'Prepared {count} existing armv7 link stubs: {output}')
